  await frame.locator('[data-settings-action=diagnostics]').click();
  await frame.locator('dialog[open] [data-diagnostics]').waitFor();
  const diagnostics=JSON.parse(await frame.locator('dialog[open] [data-diagnostics]').inputValue());
  assert.equal(diagnostics.health.databaseOk,true);assert.equal(diagnostics.limits.secretData,false);
  assert.doesNotMatch(JSON.stringify(diagnostics),/Isolated Wecom|Synthetic full-chain explanation|process-upstream-key/);
  await page.keyboard.press('Escape');
  await category('transfer');
  await frame.locator('[data-settings-action=templates]').click();
  await frame.locator('dialog[open] [data-export]').click();
  await frame.locator('dialog[open] [data-export-text]').waitFor();
