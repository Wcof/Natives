  await frame.locator('[data-financial-display] [name=quoteRefreshSeconds]').selectOption('30');
  await frame.locator('[data-financial-display] [type=submit]').click();
  await runtime.waitForFunction(async()=> (await Fund.api('GET','/api/settings')).benchmarkSymbol==='sh000905');
  assert.equal((await runtime.evaluate(()=>Fund.api('GET','/api/settings'))).quoteRefreshSeconds,30);
  await frame.locator('[data-financial-display] [name=benchmarkSymbol]').selectOption('sh000300');
  await frame.locator('[data-financial-display] [type=submit]').click();
  await runtime.waitForFunction(async()=> (await Fund.api('GET','/api/settings')).benchmarkSymbol==='sh000300');
  await category('system');
  await frame.locator('[data-settings-action=network]').click();
  await frame.locator('dialog[open] [name=mode]').selectOption('https_proxy');
  await frame.locator('dialog[open] [name=url]').fill('https://127.0.0.1/');
  await frame.locator('dialog[open] form [type=submit]').click();
  await frame.locator('dialog[open] [data-network-state]').getByText('请先验证当前代理配置。',{exact:true}).waitFor();
