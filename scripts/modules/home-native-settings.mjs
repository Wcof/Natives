  await category('notify');
  const policyForm=frame.locator('[data-notify-policy]');
  await policyForm.locator('[name=dedupMinutes]').fill('60');
  await policyForm.locator('[type=submit]').click();
  await policyForm.locator('[data-save-status]').getByText('已保存',{exact:false}).waitFor();
