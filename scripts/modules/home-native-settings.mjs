  await frame.locator(`[data-settings-action=archive-${channel.id}]`).click();
  await frame.locator(`[data-settings-action=restore-${channel.id}]`).waitFor();
  await frame.locator(`[data-settings-action=restore-${channel.id}]`).click();
  await frame.locator(`[data-settings-action=edit-${channel.id}]`).waitFor();
