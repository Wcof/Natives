  await frame.locator('dialog[open] [data-proxy-secret]').click();
  await page.locator('.module-secret-dialog input[type=password]').waitFor();
  assert.equal(await frame.locator('input[type=password]').count(),0);
  await page.keyboard.press('Escape');
  await page.keyboard.press('Escape');
  report.steps.push({name:'S06 real Native settings: unverified/private proxy rejected, original direct configuration preserved, password form only in trusted Shell; no proxy configured or credentials written'});
