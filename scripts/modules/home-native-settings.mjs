  await runtime.waitForFunction(async()=> (await Fund.api('GET','/api/settings')).sourcePriority==='em_fund_ann');
  const stored=await runtime.evaluate(()=>Fund.api('GET','/api/settings'));
  assert.equal(stored.colorMode,'intl');assert.equal(stored.linkPlatform,'xueqiu');
