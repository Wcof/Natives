import assert from 'node:assert/strict';
import { createModuleChangeBroker } from './module-change-broker.js';
const frame = {contentWindow:{postMessage(value){ messages.push(value); }}};
const messages = [], calls = [];
let subscriber, disposed = 0;
const context = {frame,generation:'g1',challenge:'secret',host:{call:async (...args)=>calls.push(args)}};
const broker = createModuleChangeBroker({appId:'fund',context:()=>context,subscribe:fn=>{subscriber=fn;return()=>disposed++;}});
const valid = {source:frame.contentWindow,data:{type:'natives:data-changed',generation:'g1',challenge:'secret'}};
broker.handle({...valid,source:{}});
broker.handle({...valid,data:{...valid.data,challenge:'wrong'}});
broker.handle({...valid,data:{...valid.data,path:'/untrusted'}});
await new Promise(resolve=>setTimeout(resolve,130));
assert.equal(calls.length,0);
broker.handle(valid);broker.handle(valid);
await new Promise(resolve=>setTimeout(resolve,130));
assert.equal(calls.length,1);
assert.equal(calls[0][0],'app:invalidate');
const originId = calls[0][1].originId;
subscriber({type:'module_changed',appId:'tokenusage'});
subscriber({type:'module_changed',appId:'fund',originId});
assert.equal(messages.length,0);
subscriber({type:'module_changed',appId:'fund',originId:'other'});
subscriber({type:'resync'});
assert.equal(messages.length,2);
assert.deepEqual(messages[0],{type:'natives:data-invalidated',generation:'g1',challenge:'secret'});
broker.handle(valid);broker.dispose();
await new Promise(resolve=>setTimeout(resolve,130));
assert.equal(calls.length,1);assert.equal(disposed,1);
console.log('module invalidation broker ownership, coalescing, resync and disposal: PASS');
